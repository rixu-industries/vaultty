//! Help → Open Source Licenses: the licenses of everything shipped inside the app (crates, bundled themes,
//! icons and logos). Many (MIT, BSD, Apache…) require including their notice when distributing the binary.
//!
//! The list comes from `assets/licenses.json`, which `cargo run -p licenses` generates (see
//! `crates/licenses`). It is embedded in the binary and read when the page opens.

use std::rc::Rc;

use crate::app::theme::{colors, mono_font, px};
use crate::components::{Input, InputEvent, InputState, icon};
use gpui_kit::assets::IconName;
use gpui_kit::component::scroll::ScrollableElement as _;
use gpui_kit::prelude::FluentBuilder;
use gpui_kit::{
    AppContext, Context, Entity, InteractiveElement, IntoElement, ParentElement, Render,
    SharedString, StatefulInteractiveElement, Styled, Subscription, UniformListScrollHandle,
    Window, div, uniform_list,
};
use serde::Deserialize;

const NOTICES: &str = include_str!("../../../assets/licenses.json");

#[derive(Deserialize)]
struct Notices {
    texts: Vec<String>,
    entries: Vec<Notice>,
}

#[derive(Deserialize)]
struct Notice {
    group: String,
    name: String,
    version: String,
    license: String,
    url: Option<String>,
    texts: Vec<usize>,
}

/// A list row: a group title or an entry (its index in `entries`).
#[derive(Clone, Copy)]
enum Row {
    Group(&'static str, usize),
    Item(usize),
}

const GROUPS: [(&str, &str); 3] = [
    ("theme", "Themes"),
    ("asset", "Icons and logos"),
    ("crate", "Libraries"),
];

pub struct Licenses {
    notices: Rc<Notices>,
    search: Entity<InputState>,
    query: String,
    rows: Rc<Vec<Row>>,
    selected: Option<usize>,
    scroll: UniformListScrollHandle,
    _subs: Vec<Subscription>,
}

impl Licenses {
    pub fn new(window: &mut Window, cx: &mut Context<Self>) -> Self {
        let notices: Notices = serde_json::from_str(NOTICES)
            .expect("assets/licenses.json is generated by crates/licenses");
        let search = cx.new(|cx| InputState::new(window, cx).placeholder("Search licenses…"));

        let subs = vec![cx.subscribe(&search, |this, input, e: &InputEvent, cx| {
            if let InputEvent::Change = e {
                this.query = input.read(cx).value().to_lowercase();
                this.rows = Rc::new(this.filter());
                cx.notify();
            }
        })];

        let mut this = Self {
            notices: Rc::new(notices),
            search,
            query: String::new(),
            rows: Rc::new(Vec::new()),
            selected: None,
            scroll: UniformListScrollHandle::new(),
            _subs: subs,
        };

        this.rows = Rc::new(this.filter());
        this
    }

    /// The rows matching the search (by name or license), grouped.
    fn filter(&self) -> Vec<Row> {
        let mut rows = Vec::new();

        for (group, title) in GROUPS {
            let items: Vec<usize> = self
                .notices
                .entries
                .iter()
                .enumerate()
                .filter(|(_, n)| n.group == group)
                .filter(|(_, n)| {
                    self.query.is_empty()
                        || n.name.to_lowercase().contains(&self.query)
                        || n.license.to_lowercase().contains(&self.query)
                })
                .map(|(i, _)| i)
                .collect();

            if !items.is_empty() {
                rows.push(Row::Group(title, items.len()));
                rows.extend(items.into_iter().map(Row::Item));
            }
        }

        rows
    }

    fn row(&self, row: Row, cx: &mut Context<Self>) -> gpui_kit::AnyElement {
        let c = colors();

        match row {
            Row::Group(title, count) => div()
                .flex()
                .items_end()
                .h(px(28.))
                .px(px(12.))
                .pb(px(4.))
                .text_size(px(11.))
                .font_weight(gpui_kit::FontWeight::MEDIUM)
                .text_color(c.panel_header_foreground)
                .child(format!("{} · {count}", title.to_uppercase()))
                .into_any_element(),
            Row::Item(ix) => {
                let n = &self.notices.entries[ix];
                let selected = self.selected == Some(ix);
                let this = cx.entity();

                let item = div()
                    .id(("license", ix))
                    .flex()
                    .items_center()
                    .w_full()
                    .gap(px(8.))
                    .h(px(28.))
                    .px(px(8.))
                    .rounded(px(4.))
                    .cursor_pointer()
                    .when(selected, |d| {
                        d.bg(c.list_active).text_color(c.list_active_foreground)
                    })
                    .when(!selected, |d| {
                        d.text_color(c.list_foreground)
                            .hover(|s| s.bg(c.list_hover))
                    })
                    .child(div().truncate().child(n.name.clone()))
                    .when(!n.version.is_empty(), |d| {
                        d.child(
                            div()
                                .flex_shrink_0()
                                .text_size(px(11.))
                                .text_color(c.muted_foreground)
                                .child(n.version.clone()),
                        )
                    })
                    .child(
                        div()
                            .ml_auto()
                            .flex_shrink_0()
                            .max_w(px(120.))
                            .truncate()
                            .text_size(px(11.))
                            .text_color(c.muted_foreground)
                            .child(n.license.clone()),
                    )
                    .on_click(move |_, _, cx| {
                        this.update(cx, |t, cx| {
                            t.selected = Some(ix);
                            cx.notify();
                        })
                    });

                div().w_full().px(px(4.)).child(item).into_any_element()
            }
        }
    }

    /// Nothing selected: what the page is for and how many there are.
    fn intro(&self) -> gpui_kit::AnyElement {
        let c = colors();
        let count = |g: &str| self.notices.entries.iter().filter(|n| n.group == g).count();

        div()
            .size_full()
            .flex()
            .flex_col()
            .items_center()
            .justify_center()
            .gap(px(10.))
            .child(icon(IconName::Heart, 28., c.muted_icon))
            .child(div().text_size(px(16.)).child(concat!("Vaultty ", env!("CARGO_PKG_VERSION"))))
            .child("Copyright (C) 2026 José García \"Ruxwez\" (Rixu Industries)")
            .child("Licensed under GPL-3.0-or-later. This program comes without any warranty.")
            .child(
                div()
                    .id("vaultty-source")
                    .cursor_pointer()
                    .text_color(c.muted_foreground)
                    .hover(|s| s.text_color(c.foreground))
                    .child("https://github.com/rixu-industries/vaultty")
                    .on_click(|_, _, cx| cx.open_url("https://github.com/rixu-industries/vaultty")),
            )
            .child(div().text_size(px(16.)).child("Built with open source"))
            .child(
                div()
                    .max_w(px(420.))
                    .text_center()
                    .text_color(c.muted_foreground)
                    .child(format!(
                        "Vaultty ships with {} libraries, {} themes and {} icon sets made by others. Choose one to read its license.",
                        count("crate"),
                        count("theme"),
                        count("asset"),
                    )),
            )
            .into_any_element()
    }

    fn detail(&self, ix: usize) -> gpui_kit::AnyElement {
        let c = colors();
        let n = &self.notices.entries[ix];
        let url = n.url.clone();

        let texts = n.texts.iter().map(|&t| {
            div()
                .p(px(14.))
                .rounded(px(6.))
                .border_1()
                .border_color(c.border)
                .bg(c.card)
                .font_family(mono_font())
                .text_size(px(12.))
                .text_color(c.card_foreground)
                .child(SharedString::from(self.notices.texts[t].clone()))
        });

        div()
            .id(("license-detail", ix))
            .size_full()
            .overflow_y_scrollbar()
            .child(
                div()
                    .flex()
                    .flex_col()
                    .gap(px(12.))
                    .max_w(px(760.))
                    .px(px(32.))
                    .py(px(24.))
                    .child(
                        div()
                            .flex()
                            .items_baseline()
                            .gap(px(8.))
                            .child(div().text_size(px(20.)).child(n.name.clone()))
                            .child(
                                div()
                                    .text_color(c.muted_foreground)
                                    .child(n.version.clone()),
                            ),
                    )
                    .child(
                        div()
                            .flex()
                            .items_center()
                            .gap(px(12.))
                            .text_color(c.muted_foreground)
                            .child(
                                div()
                                    .px(px(6.))
                                    .rounded(px(4.))
                                    .bg(c.muted)
                                    .text_size(px(12.))
                                    .child(n.license.clone()),
                            )
                            .when_some(url, |this, url| {
                                let open = url.clone();

                                this.child(
                                    div()
                                        .id("license-url")
                                        .flex()
                                        .items_center()
                                        .gap(px(4.))
                                        .min_w_0()
                                        .cursor_pointer()
                                        .hover(|s| s.text_color(c.foreground))
                                        .child(div().truncate().child(url))
                                        .child(icon(
                                            IconName::ExternalLink,
                                            12.,
                                            c.muted_foreground,
                                        ))
                                        .on_click(move |_, _, cx| cx.open_url(&open)),
                                )
                            }),
                    )
                    .children(texts),
            )
            .into_any_element()
    }
}

impl Render for Licenses {
    fn render(&mut self, _: &mut Window, cx: &mut Context<Self>) -> impl IntoElement {
        let c = colors();
        let rows = self.rows.clone();

        let list = if rows.is_empty() {
            div()
                .px(px(12.))
                .py(px(8.))
                .text_size(px(12.))
                .text_color(c.muted_foreground)
                .child("Nothing matches.")
                .into_any_element()
        } else {
            uniform_list(
                "licenses",
                rows.len(),
                cx.processor(move |this, range: std::ops::Range<usize>, _, cx| {
                    range.map(|i| this.row(rows[i], cx)).collect::<Vec<_>>()
                }),
            )
            .track_scroll(&self.scroll)
            .size_full()
            .pb(px(8.))
            .into_any_element()
        };

        let body = match self.selected {
            Some(ix) => self.detail(ix),
            None => self.intro(),
        };

        div()
            .flex()
            .size_full()
            .min_h_0()
            .child(
                div()
                    .flex()
                    .flex_col()
                    .w(px(340.))
                    .flex_shrink_0()
                    .bg(c.sidebar)
                    .text_color(c.sidebar_foreground)
                    .border_r_1()
                    .border_color(c.sidebar_border)
                    .child(
                        div()
                            .flex()
                            .items_center()
                            .h(px(34.))
                            .flex_shrink_0()
                            .px(px(12.))
                            .text_size(px(11.))
                            .font_weight(gpui_kit::FontWeight::MEDIUM)
                            .text_color(c.panel_header_foreground)
                            .child("OPEN SOURCE LICENSES"),
                    )
                    .child(
                        div().mx(px(8.)).mb(px(6.)).child(
                            Input::new(&self.search)
                                .prefix(icon(IconName::Search, 13., c.muted_icon))
                                .cleanable(true),
                        ),
                    )
                    .child(
                        div()
                            .id("licenses-list")
                            .relative()
                            .flex_1()
                            .min_h_0()
                            .child(list)
                            .vertical_scrollbar(&self.scroll),
                    ),
            )
            .child(div().flex_1().min_w_0().child(body))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// If a dependency is updated or a theme is added without regenerating the file, this fails:
    /// `cargo run -p licenses`.
    #[test]
    fn license_file_is_up_to_date() {
        let notices: Notices = serde_json::from_str(NOTICES).unwrap();
        // With `core.autocrlf`, on Windows Cargo.lock arrives with `\r\n`.
        let lock = include_str!("../../../../../Cargo.lock").replace("\r\n", "\n");

        for n in notices.entries.iter().filter(|n| n.group == "crate") {
            let entry = format!("name = \"{}\"\nversion = \"{}\"", n.name, n.version);
            assert!(
                lock.contains(&entry),
                "{} {} is no longer in Cargo.lock",
                n.name,
                n.version
            );
            assert!(!n.texts.is_empty(), "{} has no license text", n.name);
        }

        let builtin = concat!(env!("CARGO_MANIFEST_DIR"), "/../themes/builtin");
        let themes = std::fs::read_dir(builtin)
            .unwrap()
            .flatten()
            .filter(|e| e.file_name() != "vaultty")
            .count();
        let listed = notices
            .entries
            .iter()
            .filter(|n| n.group == "theme")
            .count();

        assert_eq!(listed, themes, "a bundled theme is missing its license");
    }
}
